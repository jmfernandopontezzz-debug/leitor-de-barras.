const APP_NAME = "Leitor de Barras";

/** Same host gate as the og:image injector: public names only, never loopback or Vercel system hosts. */
function publicShareHost(raw: string | null | undefined): string {
  const host = String(raw ?? "")
    .split(",")[0]
    .trim()
    .split(":")[0]
    .toLowerCase();
  if (!host || !/^[a-z0-9.-]+$/.test(host) || !host.includes(".")) return "";
  if (/^\d{1,3}(?:\.\d{1,3}){3}$/.test(host)) return "";
  if (
    host === "vercel.app" ||
    host.endsWith(".vercel.app") ||
    host === "vercel.com" ||
    host.endsWith(".vercel.com")
  ) {
    return "";
  }
  return host;
}

function xBannerContent(): string | null {
  const fromEnv = typeof process !== "undefined" ? (process.env.VITE_PUBLIC_HOSTNAME ?? "") : "";
  const host =
    publicShareHost(fromEnv) ||
    (typeof window !== "undefined" ? publicShareHost(window.location.hostname) : "");
  return host ? `https://${host}/x-banner.jpg` : null;
}

